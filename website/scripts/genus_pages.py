#!/usr/bin/env python3
"""Canonical genus -> page-URL resolver — the SINGLE SOURCE OF TRUTH for
"which page represents a given genus".

Both generators (generate_species_pages.py, generate_mosaic_pools.py) import
build_map() from here, and `python3 scripts/genus_pages.py` writes the map to
data/genus_pages.yaml so the Hugo templates (homepage mosaic) resolve the same
way. This replaces the three hand-maintained, mutually-inconsistent copies of a
hardcoded GENUS_PAGES set that previously produced 404s and "random" link
targets (links going to species pages, the bare genera index, or non-existent
genus pages).

Resolution order for a genus G:
  1. a dedicated page exists at content/collection/genera/<slug(G)>/  -> that page
  2. G is listed (via {{< collection-species/photos "G" >}}) on a non-bucket
     page                                                            -> that page
  3. G is listed on a bucket page (other-orchids/other-genera/outdoor) -> bucket
  4. G has an explicit FALLBACK_BUCKET entry                          -> bucket
  5. otherwise                                                        -> /collection/genera/  (+warn)

Every genus therefore maps to a page that actually exists: no 404s, no species
pages, no bare-index drift.
"""
from __future__ import annotations

import csv
import re
from pathlib import Path

WEB = Path(__file__).resolve().parent.parent
GENERA_DIR = WEB / "content" / "collection" / "genera"
CSV_PATH = WEB / "static" / "data" / "collection.csv"
OUT_YAML = WEB / "data" / "genus_pages.yaml"

BUCKETS = {"other-orchids", "other-genera", "outdoor"}

# Genera that have living accessions but are not (yet) shown on any genus page.
# They route to the most sensible grouping page so their species-page link and
# any mosaic tile resolve to a real page instead of nowhere. Add content for
# them to the named bucket page to make the destination meaningful.
FALLBACK_BUCKET = {
    "aldrovanda":     "outdoor",
    "amorphophallus": "other-genera",
    "ficus":          "other-genera",
    "isabelia":       "other-orchids",
    "ornitophora":    "other-orchids",
    "phragmipedium":  "other-orchids",
    "trichoglottis":  "other-orchids",
    # Aquatic + moss companions (pond / terrarium ground layer).
    "ceratophyllum":  "outdoor",
    "cladophora":     "outdoor",
    "elodea":         "outdoor",
    "lemna":          "outdoor",
    "leucobryum":     "other-genera",
}

_SHORTCODE = re.compile(r'collection-(?:species|photos)\s+(?:genus=)?"([^"]+)"')


def slug(text: str) -> str:
    s = text.lower().strip()
    s = re.sub(r"[^\w\s-]", "", s)
    s = re.sub(r"[\s_]+", "-", s)
    return s.strip("-")


def _url(page_slug: str) -> str:
    return f"/collection/genera/{page_slug}/"


def build_map() -> dict[str, str]:
    """Return {genus_slug: site-relative URL} covering every genus that has a
    dedicated page, is listed on a genus page, has a fallback, or appears alive
    in collection.csv."""
    dedicated: set[str] = set()
    listed_nonbucket: dict[str, str] = {}
    listed_bucket: dict[str, str] = {}

    for d in sorted(GENERA_DIR.iterdir()):
        if not d.is_dir():
            continue
        page = d.name
        if page not in BUCKETS:
            dedicated.add(page)
        for md in (d / "index.md", d / "index.it.md"):
            if not md.is_file():
                continue
            for m in _SHORTCODE.finditer(md.read_text(encoding="utf-8")):
                g = slug(m.group(1))
                if page in BUCKETS:
                    listed_bucket.setdefault(g, page)
                else:
                    listed_nonbucket.setdefault(g, page)

    # Gather every genus we must resolve.
    genera: set[str] = set(dedicated) | set(listed_nonbucket) | set(listed_bucket) | set(FALLBACK_BUCKET)
    if CSV_PATH.is_file():
        with CSV_PATH.open() as f:
            for row in csv.DictReader(f):
                g = (row.get("genus") or "").strip()
                if g:
                    genera.add(slug(g))

    out: dict[str, str] = {}
    unresolved: list[str] = []
    for g in sorted(genera):
        if g in dedicated:
            out[g] = _url(g)
        elif g in listed_nonbucket:
            out[g] = _url(listed_nonbucket[g])
        elif g in listed_bucket:
            out[g] = _url(listed_bucket[g])
        elif g in FALLBACK_BUCKET:
            out[g] = _url(FALLBACK_BUCKET[g])
        else:
            out[g] = "/collection/genera/"
            unresolved.append(g)
    if unresolved:
        print(f"[warn] {len(unresolved)} genera routed to the bare /collection/genera/ index "
              f"(add them to a bucket page or FALLBACK_BUCKET): {', '.join(unresolved)}")
    return out


def main() -> None:
    m = build_map()
    lines = [
        "# AUTO-GENERATED by scripts/genus_pages.py — do not edit by hand.",
        "# Canonical genus(slug) -> page URL. Consumed by the homepage mosaic",
        "# (layouts/index.html) and by the two collection generators.",
        "",
    ]
    for g, url in m.items():
        lines.append(f"{g}: {url}")
    OUT_YAML.write_text("\n".join(lines) + "\n", encoding="utf-8")
    dedicated = sum(1 for u in m.values() if u != "/collection/genera/" and u.rstrip("/").rsplit("/", 1)[-1] not in BUCKETS)
    print(f"wrote {OUT_YAML.relative_to(WEB)} — {len(m)} genera mapped "
          f"({dedicated} to dedicated pages, {len(m) - dedicated} to buckets/index)")


if __name__ == "__main__":
    main()
